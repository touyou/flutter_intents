import 'dart:io';

import 'package:app_intents_codegen/app_intents_codegen.dart';
import 'package:args/args.dart';
import 'package:path/path.dart' as path;

import 'package:app_intents_codegen/src/cli/analyze_sources.dart';

/// CLI tool for generating Kotlin code from @IntentSpec and @EntitySpec annotations.
///
/// Usage:
///   dart run app_intents_codegen:generate_kotlin [options]
///
/// Options:
///   -i, --input     Input directory containing Dart files (default: lib)
///   -o, --output    Output directory for Kotlin files (default: android/app/src/main/kotlin/generated)
///   -f, --file      Output filename (default: GeneratedAppFunctions.kt)
///   -p, --package   Kotlin package name (required)
///   -h, --help      Show usage information
void main(List<String> arguments) async {
  final parser = ArgParser()
    ..addOption(
      'input',
      abbr: 'i',
      help: 'Input directory containing Dart files',
      defaultsTo: 'lib',
    )
    ..addOption(
      'output',
      abbr: 'o',
      help: 'Output directory for Kotlin files',
      defaultsTo: 'android/app/src/main/kotlin/generated',
    )
    ..addOption(
      'file',
      abbr: 'f',
      help: 'Output filename',
      defaultsTo: 'GeneratedAppFunctions.kt',
    )
    ..addOption('package', abbr: 'p', help: 'Kotlin package name (required)')
    ..addFlag(
      'help',
      abbr: 'h',
      negatable: false,
      help: 'Show usage information',
    );

  final ArgResults results;
  try {
    results = parser.parse(arguments);
  } on FormatException catch (e) {
    stderr.writeln('Error: ${e.message}');
    stderr.writeln();
    _printUsage(parser);
    exit(1);
  }

  if (results['help'] as bool) {
    _printUsage(parser);
    exit(0);
  }

  final packageName = results['package'] as String?;
  if (packageName == null || packageName.isEmpty) {
    stderr.writeln('Error: --package option is required.');
    stderr.writeln();
    _printUsage(parser);
    exit(1);
  }

  final inputDir = results['input'] as String;
  final outputDir = results['output'] as String;
  final outputFile = results['file'] as String;

  await generateKotlin(
    inputDir: inputDir,
    outputDir: outputDir,
    outputFile: outputFile,
    packageName: packageName,
  );
}

void _printUsage(ArgParser parser) {
  stdout.writeln(
    'Generate Kotlin AppFunctions code from @IntentSpec and @EntitySpec annotations.',
  );
  stdout.writeln();
  stdout.writeln(
    'Usage: dart run app_intents_codegen:generate_kotlin [options]',
  );
  stdout.writeln();
  stdout.writeln('Options:');
  stdout.writeln(parser.usage);
}

/// Generates Kotlin code from annotated Dart files.
Future<void> generateKotlin({
  required String inputDir,
  required String outputDir,
  required String outputFile,
  required String packageName,
}) async {
  final analyzeResult = await analyzeSourceFiles(inputDir);

  if (analyzeResult.isEmpty) {
    stdout.writeln(
      'No @IntentSpec, @EntitySpec, or @EnumSpec annotations found.',
    );
    exit(0);
  }

  // Generate Kotlin code
  final generator = KotlinGenerator();
  final kotlinCode = generator.generateAll(
    packageName: packageName,
    intents: analyzeResult.intents,
    entities: analyzeResult.entities,
    enums: analyzeResult.enums,
  );

  // Write output
  final currentDir = Directory.current.path;
  final absoluteOutputDir = path.isAbsolute(outputDir)
      ? outputDir
      : path.join(currentDir, outputDir);

  final outputDirectory = Directory(absoluteOutputDir);
  if (!outputDirectory.existsSync()) {
    outputDirectory.createSync(recursive: true);
    stdout.writeln('Created output directory: $absoluteOutputDir');
  }

  final outputPath = path.join(absoluteOutputDir, outputFile);
  final file = File(outputPath);

  // Add header comment
  final output = StringBuffer()
    ..writeln('// GENERATED CODE - DO NOT MODIFY BY HAND')
    ..writeln('// Generated by app_intents_codegen')
    ..writeln(
      '// Run `dart run app_intents_codegen:generate_kotlin` to regenerate',
    )
    ..writeln()
    ..write(kotlinCode);

  file.writeAsStringSync(output.toString());

  stdout.writeln('');
  stdout.writeln('Generated Kotlin code written to: $outputPath');
  stdout.writeln('');
  stdout.writeln(
    'Add this file to your Android project to use the generated AppFunctions.',
  );
}
